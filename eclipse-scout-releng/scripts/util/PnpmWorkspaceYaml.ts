import path from 'node:path';
import {promises as fs} from 'node:fs';
import YAML from 'yaml';
import files from './files.ts';

/**
 * File name of the pnpm workspace manifest.
 */
export const WORKSPACE_MANIFEST_FILENAME = 'pnpm-workspace.yaml';

/**
 * Glob patterns of all `pnpm-workspace.yaml`-like files (`pnpm-workspace.yaml` and `pnpm-workspace-*.yaml`) up to two levels below a directory.
 */
const PNPM_WORKSPACE_FILES_GLOB = '{,*/,*/*/}pnpm-workspace{,-*}.yaml';
const PNPM_WORKSPACE_FILES_EXCLUDED_FOLDERS = new Set(['src', 'node_modules', 'target', '.git']);

/**
 * Glob patterns of directories never containing packages of the workspace (same as pnpm).
 */
const PACKAGES_EXCLUDED = ['**/node_modules/**', '**/bower_components/**'];

/**
 * Comment lines in the `overrides` of a `pnpm-workspace.yaml` enclosing the overrides generated by {@link PnpmWorkspaceYaml.updateScoutOverrides}.
 */
export const GENERATED_OVERRIDES_START_MARKER = '>>> generated by @eclipse-scout/releng, do not edit until the end marker';
export const GENERATED_OVERRIDES_END_MARKER = '<<< end of generated overrides';

/**
 * Key and anchor of the generated overrides in the format used before the markers (`scout.overrides` merged into `overrides` using `<<: *scout-overrides`).
 */
const LEGACY_SCOUT_KEY = 'scout';
const LEGACY_SCOUT_OVERRIDES_ANCHOR = 'scout-overrides';
const MERGE_KEY = '<<';

/**
 * A version (e.g. `1.2.3`), in contrast to a npm alias, a link or `-`.
 */
const NUM_VERSION_REGEX = /^\d/;

/**
 * @returns the given override selector without the versions of the parent and the dependency, e.g. `foo>bar` for `foo@1.0.0>bar@^2.0.0` or `bar` for `bar@2.0.0`.
 */
export function toSelectorWithoutVersions(selector: string): string {
  const {parent, dependency} = splitSelector(selector);
  return parent === undefined ? withoutVersion(dependency) : `${withoutVersion(parent)}>${withoutVersion(dependency)}`;
}

/**
 * @returns the dependency of the given override selector without version, e.g. `bar` for `foo@1.0.0>bar@^2.0.0` or `@scope/bar` for `@scope/bar@2.0.0`.
 */
export function toDependencyOfSelector(selector: string): string {
  return withoutVersion(splitSelector(selector).dependency);
}

/**
 * @returns the given override selector with the given version as version selector of the dependency, e.g. `foo>bar@2.0.0` for `foo>bar` and `2.0.0`.
 * The selector is returned unchanged if its dependency already has a version selector or the given version is no version (e.g. an npm alias `npm:<name>@<version>`,
 * as pnpm does not match a version selector with a dependency declared as npm alias, a link or `-`).
 */
export function toSelectorWithVersion(selector: string, version: string): string {
  const {dependency} = splitSelector(selector);
  return withoutVersion(dependency) !== dependency || !NUM_VERSION_REGEX.test(version) ? selector : `${selector}@${version}`;
}

/**
 * @returns the parent (`undefined` if there is none) and the dependency of the given override selector, e.g. `foo@1.0.0` and `bar@^2.0.0` for `foo@1.0.0>bar@^2.0.0`.
 */
function splitSelector(selector: string): { parent?: string; dependency: string } {
  // same delimiter as pnpm: a '>' not preceded by ' ', '|' or '@' (which would be part of a range like '>=1.0.0')
  const delimiter = selector.search(/[^ |@]>/);
  if (delimiter < 0) {
    return {dependency: selector};
  }
  return {parent: selector.substring(0, delimiter + 1), dependency: selector.substring(delimiter + 2)};
}

/**
 * @returns the given package selector without version, e.g. `@scope/foo` for `@scope/foo@1.0.0`.
 */
function withoutVersion(packageSelector: string): string {
  const versionDelimiter = packageSelector.indexOf('@', 1);
  return versionDelimiter > 0 ? packageSelector.substring(0, versionDelimiter) : packageSelector;
}

/**
 * An entry of the `overrides` map: either a pair or a single comment line (text without `#`).
 */
type OverridesEntry = { pair: YAML.Pair<YAML.Scalar, unknown> } | { comment: string };

/**
 * This class contains all information of a `pnpm-workspace.yaml`.
 **/
export class PnpmWorkspaceYaml {

  /**
   * The absolute path to this `pnpm-workspace.yaml`.
   */
  path: string;
  /**
   * The absolute path to the directory containing this `pnpm-workspace.yaml`.
   */
  dir: string;
  /**
   * A parsed {@link YAML} containing the content of this `pnpm-workspace.yaml`.
   */
  doc: YAML.Document<YAML.YAMLMap>;

  constructor(path: string, dir: string, doc: YAML.Document<YAML.YAMLMap>) {
    this.path = path;
    this.dir = dir;
    this.doc = doc;
  }

  /**
   * Parses a {@link PnpmWorkspaceYaml} from a `pnpm-workspace.yaml` file in the given directory.
   */
  static async parse(pnpmWorkspaceFileOrDirectory: string): Promise<PnpmWorkspaceYaml> {
    const pnpmWorkspaceYamlPath = pnpmWorkspaceFileOrDirectory.endsWith('.yaml')
      ? pnpmWorkspaceFileOrDirectory
      : path.resolve(pnpmWorkspaceFileOrDirectory, WORKSPACE_MANIFEST_FILENAME);
    const doc = YAML.parseDocument<YAML.YAMLMap>(await fs.readFile(pnpmWorkspaceYamlPath, 'utf8'));
    if (doc.errors.length) {
      throw new Error(`Error parsing yaml '${pnpmWorkspaceYamlPath}':\n${doc.errors.map(error => error.message).join('\n')}`);
    }
    return new PnpmWorkspaceYaml(pnpmWorkspaceYamlPath, path.dirname(pnpmWorkspaceYamlPath), doc);
  }

  /**
   * Gets the directory closest to the file-system root that contains a `pnpm-workspace.yaml` file.
   * The search starts at the given start directory stepping up the parent directories.
   * @returns the absolute path of the directory or `undefined` if there is none.
   */
  static async findWorkspaceFileDir(dir: string): Promise<string> {
    if (!dir) {
      return;
    }
    let pnpmWorkspaceDir: string;
    let currentDir = path.resolve(dir);
    while (true) {
      if (await files.exists(path.join(currentDir, WORKSPACE_MANIFEST_FILENAME))) {
        pnpmWorkspaceDir = currentDir;
      }
      const parentDir = path.dirname(currentDir);
      if (parentDir === currentDir) {
        // file-system root reached
        return pnpmWorkspaceDir;
      }
      currentDir = parentDir;
    }
  }

  /**
   * @param root The starting directory. It searches two levels deep starting from this directory. The root directory is included in the search.
   * @returns sorted absolute paths of `pnpm-workspace.yaml` files.
   */
  static async findPnpmWorkspaceFiles(root: string): Promise<string[]> {
    const workspaceFiles: string[] = [];
    for await (const file of fs.glob(PNPM_WORKSPACE_FILES_GLOB, {cwd: root, exclude: file => PNPM_WORKSPACE_FILES_EXCLUDED_FOLDERS.has(path.basename(file))})) {
      workspaceFiles.push(path.resolve(root, file));
    }
    return workspaceFiles.sort();
  }

  /**
   * Expands the `packages` patterns of this `pnpm-workspace.yaml` like pnpm: a package is a directory matching a pattern and containing a `package.json`.
   * Patterns starting with `!` exclude the matching directories. Directories in `node_modules` and `bower_components` are ignored.
   * @returns the sorted real paths (absolute, symbolic links resolved, as listed by pnpm) of all packages.
   */
  async getPackages(): Promise<string[]> {
    const packages = this.doc.get('packages') as YAML.YAMLSeq<YAML.Scalar<string>>;
    const patterns = (packages?.items ?? []).map(item => item.value);
    const includes = patterns.filter(pattern => !pattern.startsWith('!')).map(pattern => path.posix.join(pattern, 'package.json'));
    const excludes = patterns.filter(pattern => pattern.startsWith('!')).map(pattern => path.posix.normalize(pattern.substring(1)).replace(/\/$/, ''));
    const packageDirs = new Set<string>();
    for await (const packageJson of fs.glob(includes, {cwd: this.dir, exclude: [...PACKAGES_EXCLUDED, ...excludes]})) {
      packageDirs.add(await fs.realpath(path.resolve(this.dir, path.dirname(packageJson))));
    }
    return [...packageDirs].sort();
  }

  /**
   * Disables the generated overrides by turning them into comment lines between the markers. The overrides written manually are not changed.
   * A `pnpm-workspace.yaml` in the legacy format (`scout.overrides`) is migrated.
   */
  disableScoutOverrides() {
    this._updateGeneratedOverrides(null, false);
  }

  /**
   * Enables the generated overrides disabled by {@link disableScoutOverrides}.
   * A `pnpm-workspace.yaml` in the legacy format (`scout.overrides`) is migrated.
   */
  enableScoutOverrides() {
    this._updateGeneratedOverrides(null, true);
  }

  /**
   * Migrates a `pnpm-workspace.yaml` in the legacy format (`scout.overrides`). The migrated overrides are enabled, as the legacy ones.
   * @returns `true` if the legacy format was migrated, `false` if there is no `scout.overrides` block.
   */
  migrateLegacyScoutOverrides(): boolean {
    if (this._getLegacyScoutOverrides() === null) {
      return false;
    }
    this.enableScoutOverrides();
    return true;
  }

  /**
   * @returns the enabled generated overrides (between the markers or in the legacy format), i.e. the ones pnpm applies. Disabled overrides are not returned.
   */
  getEnabledScoutOverrides(): Record<string, string> {
    const overrides = this.doc.get('overrides', true);
    if (!YAML.isMap(overrides)) {
      return {};
    }
    const entries = this._toEntries(overrides as YAML.YAMLMap<YAML.Scalar, unknown>);
    const {start, end} = this._findGeneratedRange(entries);
    if (start < 0) {
      return this._getLegacyScoutOverrides() ?? {};
    }
    return this._readGeneratedOverrides(entries.slice(start + 1, end).filter(entry => 'pair' in entry));
  }

  /**
   * Replaces the generated overrides between the markers in the `overrides` with the given overrides. The markers are added at the end of the `overrides` if missing.
   * Overrides written manually (outside the markers) are not changed and take precedence: a given override with the same parent and dependency as a manual one
   * is not written, regardless of the versions in the selectors (see {@link toSelectorWithoutVersions}).
   * A `pnpm-workspace.yaml` in the legacy format (`scout.overrides`) is migrated.
   */
  updateScoutOverrides(newScoutOverrides: Record<string, string>) {
    this._updateGeneratedOverrides(newScoutOverrides, true);
  }

  /**
   * Writes the generated overrides between the markers in the `overrides`.
   * @param generatedOverrides the overrides to write or `null` to keep the current generated overrides.
   * @param enabled `true` to write the generated overrides as entries, `false` to write them as comment lines.
   */
  protected _updateGeneratedOverrides(generatedOverrides: Record<string, string> | null, enabled: boolean) {
    const legacyOverrides = this._getLegacyScoutOverrides();
    const overrides = this._getOverridesMap(generatedOverrides !== null || legacyOverrides !== null);
    if (!overrides) {
      return;
    }

    // remove the legacy merge key, the generated overrides are placed at its position
    const entries = this._toEntries(overrides);
    const mergeKeyIndex = entries.findIndex(entry => 'pair' in entry && this._isLegacyMergeKey(entry.pair));
    const withoutMergeKey = entries.filter(entry => !('pair' in entry && this._isLegacyMergeKey(entry.pair)));

    let {start, end} = this._findGeneratedRange(withoutMergeKey);
    let currentOverrides: Record<string, string>;
    if (start >= 0) {
      currentOverrides = this._readGeneratedOverrides(withoutMergeKey.slice(start + 1, end));
    } else if (legacyOverrides !== null || generatedOverrides !== null) {
      currentOverrides = legacyOverrides ?? {};
      start = mergeKeyIndex >= 0 ? mergeKeyIndex : withoutMergeKey.length;
      withoutMergeKey.splice(start, 0, {comment: ` ${GENERATED_OVERRIDES_START_MARKER}`}, {comment: ` ${GENERATED_OVERRIDES_END_MARKER}`});
      end = start + 1;
    } else {
      // nothing generated
      return;
    }

    // overrides written manually take precedence: no override is generated for the same parent and dependency, regardless of the versions in the selectors
    // (pnpm would prefer the generated 'lodash@4.17.21' over the manual 'lodash', as its version selector is more specific)
    const manualSelectors = new Set([...withoutMergeKey.slice(0, start), ...withoutMergeKey.slice(end + 1)]
      .filter(entry => 'pair' in entry)
      .map((entry: { pair: YAML.Pair<YAML.Scalar, unknown> }) => toSelectorWithoutVersions(String(entry.pair.key.value))));
    const generatedEntries: OverridesEntry[] = Object.entries(generatedOverrides ?? currentOverrides)
      .filter(([key]) => !manualSelectors.has(toSelectorWithoutVersions(key)))
      .map(([key, value]) => enabled
        ? {pair: new YAML.Pair(new YAML.Scalar(key), new YAML.Scalar(value))}
        : {comment: ` ${YAML.stringify({[key]: value}).trimEnd()}`});
    withoutMergeKey.splice(start + 1, end - start - 1, ...generatedEntries);

    this._applyEntries(overrides, withoutMergeKey);
    this.doc.delete(LEGACY_SCOUT_KEY);
  }

  /**
   * @returns the overrides of the legacy `scout.overrides` block or `null` if there is none.
   * The overridden version is added as version selector (see {@link toSelectorWithVersion}): the legacy overrides apply regardless of the declared range,
   * so they may force a version outside of it. With the version selector, pnpm applies them only where the declared range includes the version.
   */
  protected _getLegacyScoutOverrides(): Record<string, string> | null {
    const scout = this.doc.get(LEGACY_SCOUT_KEY, true);
    if (!YAML.isMap(scout)) {
      return null;
    }
    const scoutOverrides = scout.get('overrides', true);
    if (!YAML.isMap(scoutOverrides)) {
      return {};
    }
    // the text of a plain scalar as written (e.g. '1.0' instead of the number 1)
    const toText = (node: unknown) => YAML.isScalar(node) ? node.source ?? String(node.value) : String(node);
    return Object.fromEntries(scoutOverrides.items.map(pair => {
      const version = toText(pair.value);
      return [toSelectorWithVersion(toText(pair.key), version), version];
    }));
  }

  protected _isLegacyMergeKey(pair: YAML.Pair<YAML.Scalar, unknown>): boolean {
    return pair.key?.value === MERGE_KEY && YAML.isAlias(pair.value) && pair.value.source === LEGACY_SCOUT_OVERRIDES_ANCHOR;
  }

  /**
   * @param create whether to create the `overrides` if missing.
   * @returns the `overrides` map or `null` if there is none and create is `false`.
   */
  protected _getOverridesMap(create: boolean): YAML.YAMLMap<YAML.Scalar, unknown> | null {
    const overrides = this.doc.get('overrides', true);
    if (YAML.isMap(overrides)) {
      return overrides as YAML.YAMLMap<YAML.Scalar, unknown>;
    }
    if (overrides !== undefined && !(YAML.isScalar(overrides) && overrides.value === null)) {
      throw new Error(`'overrides' in '${this.path}' is not a map.`);
    }
    // an empty value may contain the markers as comments
    const comment = (overrides as YAML.Scalar)?.comment;
    if (!create && !comment) {
      return null;
    }
    const map = new YAML.YAMLMap<YAML.Scalar, unknown>();
    map.comment = comment;
    this.doc.set('overrides', map);
    return map;
  }

  /**
   * @returns the pairs and comment lines of the given map in the order they appear in the file.
   */
  protected _toEntries(map: YAML.YAMLMap<YAML.Scalar, unknown>): OverridesEntry[] {
    const entries: OverridesEntry[] = [];
    const commentLines = (comment: string) => comment ? comment.split('\n').map(line => ({comment: line})) : [];
    // comments before the first pair belong to the map
    entries.push(...commentLines(map.commentBefore));
    for (const pair of map.items) {
      // keys of pairs created by the API instead of the parser may be plain values
      if (!YAML.isScalar(pair.key)) {
        pair.key = new YAML.Scalar(pair.key);
      }
      entries.push(...commentLines(pair.key.commentBefore));
      entries.push({pair});
    }
    entries.push(...commentLines(map.comment));
    return entries;
  }

  /**
   * Replaces the pairs and comments of the given map with the given entries (see {@link _toEntries}).
   */
  protected _applyEntries(map: YAML.YAMLMap<YAML.Scalar, unknown>, entries: OverridesEntry[]) {
    const items: YAML.Pair<YAML.Scalar, unknown>[] = [];
    let comments: string[] = [];
    for (const entry of entries) {
      if ('comment' in entry) {
        comments.push(entry.comment);
        continue;
      }
      entry.pair.key.commentBefore = comments.length ? comments.join('\n') : undefined;
      comments = [];
      items.push(entry.pair);
    }
    map.items = items;
    map.commentBefore = undefined;
    map.comment = comments.length ? comments.join('\n') : undefined;
    // an empty block map cannot be written, an empty flow map is followed by the comments
    map.flow = !items.length;
  }

  /**
   * @returns the indices of the start and end marker in the given entries or `-1` if there are no markers.
   */
  protected _findGeneratedRange(entries: OverridesEntry[]): { start: number; end: number } {
    const indicesOf = (marker: string) => entries
      .map((entry, index) => 'comment' in entry && entry.comment.trim() === marker ? index : -1)
      .filter(index => index >= 0);
    const starts = indicesOf(GENERATED_OVERRIDES_START_MARKER);
    const ends = indicesOf(GENERATED_OVERRIDES_END_MARKER);
    if (!starts.length && !ends.length) {
      return {start: -1, end: -1};
    }
    if (starts.length !== 1 || ends.length !== 1 || ends[0] < starts[0]) {
      throw new Error(`The 'overrides' in '${this.path}' must contain the comment '# ${GENERATED_OVERRIDES_START_MARKER}' followed by '# ${GENERATED_OVERRIDES_END_MARKER}' exactly once.`);
    }
    return {start: starts[0], end: ends[0]};
  }

  /**
   * @returns the overrides of the given entries between the markers, either enabled (pairs) or disabled (comment lines).
   * Other comment lines are ignored (see {@link _parseDisabledOverride}).
   */
  protected _readGeneratedOverrides(entries: OverridesEntry[]): Record<string, string> {
    const overrides: Record<string, string> = {};
    for (const entry of entries) {
      if ('pair' in entry) {
        overrides[String(entry.pair.key.value)] = String(YAML.isScalar(entry.pair.value) ? entry.pair.value.value : entry.pair.value);
      } else {
        Object.assign(overrides, this._parseDisabledOverride(entry.comment));
      }
    }
    return overrides;
  }

  /**
   * @returns the override of the given comment line written by {@link disableScoutOverrides} (e.g. `{lodash@4.17.21: '4.17.21'}` for ` lodash@4.17.21: 4.17.21`),
   *   or `null` if the comment line is no such override. An override is a single pair whose value is a version or an npm alias (`npm:<name>@<version>`).
   */
  protected _parseDisabledOverride(comment: string): Record<string, string> | null {
    let parsed: unknown;
    try {
      parsed = YAML.parse(comment);
    } catch {
      return null;
    }
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
      return null;
    }
    const entries = Object.entries(parsed);
    const version = String(entries[0]?.[1]);
    if (entries.length !== 1 || !(NUM_VERSION_REGEX.test(version) || version.startsWith('npm:'))) {
      return null;
    }
    return {[entries[0][0]]: version};
  }

  /**
   * Writes this `pnpm-workspace.yaml` to the disk.
   */
  async flush(): Promise<void> {
    const content = YAML.stringify(this.doc);
    return await fs.writeFile(this.path, content, 'utf8');
  }
}
