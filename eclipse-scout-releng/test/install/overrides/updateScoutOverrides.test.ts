/**
 * Problem: an override replacing the range of a peer dependency influences how pnpm resolves this peer dependency. If such an override is removed, the next
 * install may resolve the peer dependency to another version, so the installed dependencies and the overrides computed from them change once more.
 *
 * Sample:
 * - Project `a` depends on `@types/node: ^24.0.0` (resolved to 24.12.0), project `b` on `@types/node: 26.6.6`.
 * - Project `c` depends on `@rushstack/worker-pool`, which declares the optional peer dependency `@types/node: *`. `c` does not provide `@types/node`.
 * - The `pnpm-workspace.yaml` contains the global override `@types/node@24.12.0: 24.12.0`: migrated from the legacy override `"@types/node": 24.12.0`, or
 *   generated before `c` added `@rushstack/worker-pool` (when `@types/node` was no peer dependency yet).
 *
 * 1. The first install applies the global override to the peer range `*` of `@rushstack/worker-pool` too, so its peer is resolved to `@types/node@24.12.0`.
 * 2. As `@types/node` is a peer dependency now, the computed overrides contain overrides with parent only (`a>@types/node@24.12.0`): the global override is removed.
 * 3. The next install resolves the peer range `*` without override: pnpm takes the highest version present, `@types/node@26.6.6`. Its dependency
 *    `undici-types@8.9.0` is now used by `c` as well, so e.g. a nested `pnpm-workspace.yaml` containing `c` gets a new override.
 *
 * Therefore, {@link updateScoutOverrides} reports the removed override of the peer dependency, and the scout install repeats the install once.
 */
describe('updateScoutOverrides', () => {

  it('reports a removed global override of a peer dependency (see the problem description above)', async () => {
    await withSampleWorkspace(async (dir, dependencyGraph) => {
      await fs.writeFile(join(dir, 'pnpm-workspace.yaml'),
        'packages:\n' +
        '  - a\n' +
        '  - b\n' +
        '  - c\n' +
        'overrides:\n' +
        '  # >>> generated by @eclipse-scout/releng, do not edit until the end marker\n' +
        '  "@types/node@24.12.0": 24.12.0\n' +
        '  # <<< end of generated overrides\n');

      assert.equal(await updateScoutOverrides(join(dir, 'pnpm-workspace.yaml'), dependencyGraph, dependencyConvergenceLogLevel.NONE), true);
      assert.match(await fs.readFile(join(dir, 'pnpm-workspace.yaml'), 'utf8'), /^ {2}a>"?@types\/node@24\.12\.0"?: 24\.12\.0$/m);
    });
  });

  it('reports a removed override of a peer dependency in the legacy format', async () => {
    await withSampleWorkspace(async (dir, dependencyGraph) => {
      await fs.writeFile(join(dir, 'pnpm-workspace.yaml'),
        'packages:\n' +
        '  - a\n' +
        '  - b\n' +
        '  - c\n' +
        'scout:\n' +
        '  overrides: &scout-overrides\n' +
        '    "@types/node": 24.12.0\n' +
        'overrides:\n' +
        '  <<: *scout-overrides\n');

      assert.equal(await updateScoutOverrides(join(dir, 'pnpm-workspace.yaml'), dependencyGraph, dependencyConvergenceLogLevel.NONE), true);
    });
  });

  it('does not report anything if the overrides of the peer dependency are kept', async () => {
    await withSampleWorkspace(async (dir, dependencyGraph) => {
      await fs.writeFile(join(dir, 'pnpm-workspace.yaml'),
        'packages:\n' +
        '  - a\n' +
        '  - b\n' +
        '  - c\n' +
        'overrides:\n' +
        '  # >>> generated by @eclipse-scout/releng, do not edit until the end marker\n' +
        '  a>@types/node@24.12.0: 24.12.0\n' +
        '  # <<< end of generated overrides\n');

      assert.equal(await updateScoutOverrides(join(dir, 'pnpm-workspace.yaml'), dependencyGraph, dependencyConvergenceLogLevel.NONE), false);
    });
  });

  it('does not report the removed overrides if they were disabled', async () => {
    await withSampleWorkspace(async (dir, dependencyGraph) => {
      await fs.writeFile(join(dir, 'pnpm-workspace.yaml'),
        'packages:\n' +
        '  - a\n' +
        '  - b\n' +
        '  - c\n' +
        'overrides: {}\n' +
        '  # >>> generated by @eclipse-scout/releng, do not edit until the end marker\n' +
        '  # "@types/node@24.12.0": 24.12.0\n' +
        '  # <<< end of generated overrides\n');

      assert.equal(await updateScoutOverrides(join(dir, 'pnpm-workspace.yaml'), dependencyGraph, dependencyConvergenceLogLevel.NONE), false);
    });
  });
});

describe('isPeerDependencyOverrideRemoved', () => {

  const peerDependencyAliases = new Set(['@types/node']);

  it('returns true if an override of a peer dependency is not contained in the new overrides', () => {
    assert.equal(isPeerDependencyOverrideRemoved({'@types/node@24.12.0': '24.12.0'}, {'a>@types/node@24.12.0': '24.12.0'}, peerDependencyAliases), true);
    assert.equal(isPeerDependencyOverrideRemoved({'@rushstack/worker-pool>@types/node@24.12.0': '24.12.0'}, {}, peerDependencyAliases), true);
  });

  it('returns false if all overrides of peer dependencies are kept', () => {
    assert.equal(isPeerDependencyOverrideRemoved({'a>@types/node@24.12.0': '24.12.0'}, {'a>@types/node@24.12.0': '24.12.0'}, peerDependencyAliases), false);
  });

  it('returns false if only overrides of other dependencies are removed', () => {
    assert.equal(isPeerDependencyOverrideRemoved({'undici-types@7.16.0': '7.16.0', '@types/node-fetch@2.6.13': '2.6.13'}, {}, peerDependencyAliases), false);
  });
});

/**
 * Creates the projects `a`, `b` and `c` of the sample described above and the dependency graph of their installation.
 */
async function withSampleWorkspace(callback: (dir: string, dependencyGraph: PnpmDependencyGraph) => Promise<void>): Promise<void> {
  const dir = await fs.realpath(await fs.mkdtemp(join(tmpdir(), 'update-scout-overrides-test-')));
  const writePackageJson = async (packageDir: string, packageJson: object) => {
    await fs.mkdir(packageDir, {recursive: true});
    await fs.writeFile(join(packageDir, 'package.json'), JSON.stringify(packageJson));
  };
  const store = (name: string) => join(dir, 'node_modules', '.pnpm', name.replace('/', '+'), 'node_modules', name);
  const typesNode = (version: string) => ({from: '@types/node', version, path: store(`@types/node@${version}`)});
  try {
    await writePackageJson(join(dir, 'a'), {name: 'a', version: '1.0.0', dependencies: {'@types/node': '^24.0.0'}});
    await writePackageJson(join(dir, 'b'), {name: 'b', version: '1.0.0', dependencies: {'@types/node': '26.6.6'}});
    await writePackageJson(join(dir, 'c'), {name: 'c', version: '1.0.0', dependencies: {'@rushstack/worker-pool': '0.4.9'}});
    await writePackageJson(store('@rushstack/worker-pool'), {
      name: '@rushstack/worker-pool', version: '0.4.9', peerDependencies: {'@types/node': '*'}, peerDependenciesMeta: {'@types/node': {optional: true}}
    });
    const projects: PnpmListOutput = [
      {name: 'a', version: '1.0.0', path: join(dir, 'a'), private: false, dependencies: {'@types/node': typesNode('24.12.0')}},
      {name: 'b', version: '1.0.0', path: join(dir, 'b'), private: false, dependencies: {'@types/node': typesNode('26.6.6')}},
      {
        name: 'c', version: '1.0.0', path: join(dir, 'c'), private: false, dependencies: {
          '@rushstack/worker-pool': {from: '@rushstack/worker-pool', version: '0.4.9', path: store('@rushstack/worker-pool'), dependencies: {'@types/node': typesNode('24.12.0')}}
        }
      }
    ];
    const consoleLog = mock.method(console, 'log', () => undefined);
    try {
      await callback(dir, new PnpmDependencyGraph(projects));
    } finally {
      consoleLog.mock.restore();
    }
  } finally {
    await fs.rm(dir, {recursive: true});
  }
}
